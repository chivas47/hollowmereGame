ORDER = ['emberbomb', 'blastbomb', 'greatbomb', 'slimepress', 'chest', 'bigchest', 'sign', 'farmcomputer', 'minibin', 'sprinkler',
         'sprinkler2', 'sprinkler3', 'crock', 'churn', 'vat', 'brewbarrel', 'eggpress', 'loom', 'oilpress', 'beebox', 'gemcopier', 'dryer',
         'mushroomlog', 'incubator', 'silo', 'smoker', 'furnace', 'kiln', 'lightningrod', 'lantern', 'seedmaker', 'gardenpot']
BOTTOM = 29   # each object's last row; its outline is on row 30 and its shadow on row 31

def hexc(h): h = h.lstrip('#'); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
def outline(c): return tuple(int(v * 0.42 + w * 0.12) for v, w in zip(c, (60, 36, 24)))

def frame(kind):
    rows = ART[kind]
    y0 = BOTTOM - len(rows) + 1
    px = {}
    for j, row in enumerate(rows):
        assert len(row) <= W, (kind, row)
        for i, ch in enumerate(row):
            if ch != '.': px[(i, y0 + j)] = hexc(PAL[ch])
    out = {}
    xs = [x for x, y in px if y == BOTTOM] or [x for x, _ in px]
    for x in range(min(xs) - 1, max(xs) + 2):
        if 0 <= x < W: out[(x, H - 1)] = (0, 0, 0, 40 if x in (min(xs) - 1, max(xs) + 1) else 64)
    for (i, j) in sorted(px, key=lambda q: (q[1], q[0])):
        for q in ((i + 1, j), (i - 1, j), (i, j - 1), (i, j + 1)):
            if q in px or not (0 <= q[0] < W and 0 <= q[1] < H - 1): continue
            if q not in out: out[q] = outline(px[(i, j)]) + (255,)
    for q, c in px.items(): out[q] = c + (255,)
    return out

def build(path, preview=None):
    img = Image.new('RGBA', (W * len(ORDER), H), (0, 0, 0, 0))
    for n, kind in enumerate(ORDER):
        for (x, y), c in frame(kind).items(): img.putpixel((n * W + x, y), c)
    img.save(path, optimize=True)
    if preview:
        bg = Image.new('RGBA', img.size, (118, 168, 88, 255)); bg.alpha_composite(img)
        out = Image.new('RGBA', (W * 16, H * 2))
        for i in range(len(ORDER)): out.paste(bg.crop((i * W, 0, i * W + W, H)), ((i % 16) * W, (i // 16) * H))
        out.resize((out.width * 5, out.height * 5), Image.NEAREST).save(preview)

if __name__ == '__main__':
    build(sys.argv[1] if len(sys.argv) > 1 else 'assets/sprites/placed.png', sys.argv[2] if len(sys.argv) > 2 else None)

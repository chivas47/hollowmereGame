function emptyGrid() {
  return Array.from({ length: H }, (_, y) =>
    Array.from({ length: W }, (_, x) => (x === 0 || y === 0 || x === W - 1 || y === H - 1 ? 'T' : 'g')));
}
const put = (m, list, t) => list.forEach(([x, y]) => { m[y][x] = t; });
const fill = (m, x0, y0, x1, y1, t) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) m[y][x] = t; };

export function farmGrid() {
  const m = emptyGrid();
  fill(m, 1, 1, 5, 3, 'H'); m[3][3] = 'D';
  fill(m, 19, 1, 21, 3, 'S');
  m[3][8] = 'B'; m[3][12] = 'W'; m[3][15] = 'K';
  m[5][6] = 'b';   // the pet's water bowl (systems/pets.js)
  fill(m, 1, 4, W - 2, 4, 'P'); m[4][W - 1] = 'E'; m[4][0] = 'E';
  put(m, [[22, 1], [22, 2], [22, 3], [6, 1], [7, 1], [16, 1], [17, 1], [1, 14], [22, 14], [22, 13], [1, 13]], 'T');
  return m;
}

function wildsGrid() {
  const m = emptyGrid();
  fill(m, 0, 4, 12, 4, 'P'); m[4][0] = 'E';
  fill(m, 12, 2, 12, 3, 'P');
  fill(m, 11, 1, 13, 1, 'M');
  fill(m, 11, 5, 11, 11, 'P');
  fill(m, 15, 8, 20, 12, 'O');
  put(m, [[15, 8], [20, 12], [20, 8], [15, 12]], 'g');
  put(m, [[3, 2], [6, 1], [9, 2], [14, 2], [17, 1], [20, 3], [2, 7], [5, 9], [8, 13], [3, 13], [14, 13], [21, 6], [13, 6], [18, 14], [7, 8]], 'T');
  put(m, [[7, 6], [4, 11], [18, 5], [9, 10]], 'R');
  return m;
}

function villageGrid() {
  const m = emptyGrid();
  [[1, 2], [5, 2], [16, 2], [20, 2]].forEach(([x, y]) => fill(m, x, y, x + 2, y + 1, 'V'));
  fill(m, 1, 4, W - 2, 4, 'P');
  fill(m, 8, 6, 15, 11, 'P');
  put(m, [[9, 5], [14, 5]], 'P');
  fill(m, 16, 8, W - 2, 8, 'P'); m[8][W - 1] = 'E';
  fill(m, 11, 5, 12, 5, 'Q');
  fill(m, 11, 8, 12, 9, 'F');
  fill(m, 13, 11, 14, 11, 'J');
  put(m, [[3, 9], [5, 12], [2, 14], [19, 12], [21, 10], [17, 14], [12, 14], [6, 7]], 'T');
  return m;
}

function greenhouseGrid() {
  const m = Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) => (x === 0 || y === 0 || x === W - 1 || y === H - 1 ? 'w' : 'p')));
  fill(m, 2, 4, 22, 9, 'g');   // 21 x 6 beds
  m[12][2] = 'W';
  m[H - 1][12] = 'E';
  return m;
}

// The farmhouse inside (v24). tier: the house upgrade (0 cottage, 1 adds the kitchen, 2 the nursery,
// 3 the cellar); renos: renovation keys (data/furniture.js). Tiles: . nothing (solid), I wall, h floor,
// Z bed, l catalogue lectern, n kitchen counter, o stove, x crib, v cask, E the front door.
export function houseGrid(tier = 0, renos = []) {
  const m = Array.from({ length: H }, () => Array.from({ length: W }, () => '.'));
  const room = (x0, y0, x1, y1) => { fill(m, x0 - 1, y0 - 2, x1 + 1, y1 + 1, 'I'); fill(m, x0, y0, x1, y1, 'h'); };
  room(6, 3, 17, 11);
  if (tier >= 1) { room(19, 3, 22, 8); fill(m, 18, 6, 18, 7, 'h'); put(m, [[19, 3], [20, 3], [22, 3]], 'n'); m[3][21] = 'o'; }
  if (tier >= 2) { room(1, 3, 4, 8); fill(m, 5, 6, 5, 7, 'h'); m[3][2] = 'x'; }
  if (tier >= 3) { fill(m, 18, 9, 23, 15, 'I'); fill(m, 19, 10, 22, 14, 'h'); m[9][20] = 'h'; put(m, [[19, 14], [21, 14], [22, 14]], 'v'); }
  if (!renos.includes('openplan')) fill(m, 10, 3, 10, 5, 'I');   // the bed corner's wall
  if (renos.includes('nook')) fill(m, 12, 2, 13, 2, 'h');
  put(m, [[7, 3], [7, 4]], 'Z'); m[3][16] = 'l';
  m[12][11] = 'E';
  return m;
}

// The shed inside (v30): one plank room. Machines, decorations and furniture go on its floor (h).
function shedGrid() {
  const m = Array.from({ length: H }, () => Array.from({ length: W }, () => '.'));
  fill(m, 3, 1, 20, 12, 'I'); fill(m, 4, 3, 19, 11, 'h');
  m[12][11] = 'E';
  return m;
}


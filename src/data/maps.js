// Maps are data. Tile legend:
//   g grass (farmable on the farm)   P path   E exit to another map
//   T tree   R rock   O pond water   q quarry floor   z sand (farm layouts, data/layouts.js)
//   H house   D door   S shop stall   B shipping bin   W well
//   K workbench   C chicken coop (placed at runtime by systems/coop.js)   M mine entrance
//   A barn (placed at runtime by systems/barn.js)   Y crafted object (placed at runtime by systems/placeables.js)
//   V village cottage   Q quest board   F fountain   J festival table
//   G greenhouse (placed at runtime by systems/greenhouse.js)   inside it: w glass wall, p floor, g bed, W water trough
// Mine floors are generated by systems/mine.js:
//   f cave floor   X cave wall   r/c/i stone, copper and iron rocks   U ladder up   L ladder down
// objects: art drawn on top of the tiles (see render/tiles.js OBJECT_ART).
// exits: "x,y" of an E tile -> where it leads.
import { W, H } from '../core/constants.js';

export const SOLID = new Set(['T', 'H', 'D', 'B', 'W', 'S', 'O', 'R', 'K', 'C', 'M', 'X', 'r', 'c', 'i', 'U', 'L', 'A', 'Y', 'V', 'Q', 'F', 'J', 'G', 'w']);

function emptyGrid() {
  return Array.from({ length: H }, (_, y) =>
    Array.from({ length: W }, (_, x) => (x === 0 || y === 0 || x === W - 1 || y === H - 1 ? 'T' : 'g')));
}
const put = (m, list, t) => list.forEach(([x, y]) => { m[y][x] = t; });
const fill = (m, x0, y0, x1, y1, t) => { for (let y = y0; y <= y1; y++) for (let x = x0; x <= x1; x++) m[y][x] = t; };

export function farmGrid() {
  const m = emptyGrid();
  fill(m, 1, 1, 5, 3, 'H'); m[3][3] = 'D';
  fill(m, 19, 1, 21, 3, 'S');
  m[3][8] = 'B'; m[3][12] = 'W'; m[3][15] = 'K';
  fill(m, 1, 4, W - 2, 4, 'P'); m[4][W - 1] = 'E'; m[4][0] = 'E';
  put(m, [[22, 1], [22, 2], [22, 3], [6, 1], [7, 1], [16, 1], [17, 1], [1, 14], [22, 14], [22, 13], [1, 13]], 'T');
  return m;
}

function wildsGrid() {
  const m = emptyGrid();
  fill(m, 0, 4, 12, 4, 'P'); m[4][0] = 'E';
  fill(m, 12, 2, 12, 3, 'P');
  fill(m, 11, 1, 13, 1, 'M');
  fill(m, 11, 5, 11, 11, 'P');
  fill(m, 15, 8, 20, 12, 'O');
  put(m, [[15, 8], [20, 12], [20, 8], [15, 12]], 'g');
  put(m, [[3, 2], [6, 1], [9, 2], [14, 2], [17, 1], [20, 3], [2, 7], [5, 9], [8, 13], [3, 13], [14, 13], [21, 6], [13, 6], [18, 14], [7, 8]], 'T');
  put(m, [[7, 6], [4, 11], [18, 5], [9, 10]], 'R');
  return m;
}

function villageGrid() {
  const m = emptyGrid();
  [[1, 2], [5, 2], [16, 2], [20, 2]].forEach(([x, y]) => fill(m, x, y, x + 2, y + 1, 'V'));
  fill(m, 1, 4, W - 2, 4, 'P');
  fill(m, 8, 6, 15, 11, 'P');
  put(m, [[9, 5], [14, 5]], 'P');
  fill(m, 16, 8, W - 2, 8, 'P'); m[8][W - 1] = 'E';
  fill(m, 11, 5, 12, 5, 'Q');
  fill(m, 11, 8, 12, 9, 'F');
  fill(m, 13, 11, 14, 11, 'J');
  put(m, [[3, 9], [5, 12], [2, 14], [19, 12], [21, 10], [17, 14], [12, 14], [6, 7]], 'T');
  return m;
}

function greenhouseGrid() {
  const m = Array.from({ length: H }, (_, y) => Array.from({ length: W }, (_, x) => (x === 0 || y === 0 || x === W - 1 || y === H - 1 ? 'w' : 'p')));
  fill(m, 2, 4, 22, 9, 'g');   // 21 x 6 beds
  m[12][2] = 'W';
  m[H - 1][12] = 'E';
  return m;
}


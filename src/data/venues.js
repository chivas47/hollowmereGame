// The tile in front of a building's door, outside: below the middle of its bottom row (above its top row when you
// come out facing up). Read from the map's grid, so the coop and barn follow wherever they were placed. null: not built.
export function venueFront(V, grid) {
  const cells = [];
  grid.forEach((row, y) => row.forEach((t, x) => { if (V.tiles.includes(t)) cells.push([x, y]); }));
  if (!cells.length) return null;
  const up = V.dir === 'up', edge = up ? Math.min(...cells.map((c) => c[1])) : Math.max(...cells.map((c) => c[1]));
  const xs = cells.filter((c) => c[1] === edge).map((c) => c[0]);
  return [xs[Math.floor(xs.length / 2)], edge + (up ? -1 : 1)];
}

